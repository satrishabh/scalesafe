def esc(s):
    return insights.esc(s)


def reg_card(code, name, desc, chips, filt):
    what = "my" if code == "+" else f"my {esc(code)}"
    links = [f'<a href="/#contact">Map {what} obligations — book a walkthrough</a>']
    if filt:
        links.append(f'<a href="/insights/?type={filt}">Read the {esc(code)} briefings</a>')
    chips_html = "".join(f"<em>{esc(c)}</em>" for c in chips)
    other = " sol-other" if code == "+" else ""
    body = (f"<div><h3>{esc(name)}</h3><p>{esc(desc)}</p></div>" if other
            else f"<h3>{esc(name)}</h3>\n  <p>{esc(desc)}</p>")
    return f"""<article class="sol-reg{other}">
  <span class="badge-code" aria-hidden="true">{esc(code)}</span>
  {body}
  <div class="chips" aria-label="Typical topics">{chips_html}</div>
  <div class="sol-links">{"".join(links)}</div>
</article>"""


def job_block(i, job, why, platform, services, more):
    def col(title, rows):
        lis = "".join(f"<li><b>{esc(t)}</b><span>{esc(d)}</span></li>" for t, d in rows)
        return f"<div><h4>{title}</h4><ul>{lis}</ul></div>"
    cols = [col("In the platform", platform) if platform else "", col("With our team", services) if services else ""]
    one = " sol-one" if not (platform and services) else ""
    more_html = f'<p style="margin:12px 0 0"><a class="sol-more" href="{more[1]}">{esc(more[0])}</a></p>' if more else ""
    return f"""<article class="sol-job" id="job-{i}">
  <div><span class="num">{i:02d}</span><h3>{esc(job)}</h3><p>{esc(why)}</p>{more_html}</div>
  <div class="sol-cols{one}">{"".join(cols)}</div>
</article>"""


def build(root):
    home_path = os.path.join(root, "index.html")
    home = insights.read(home_path)
    c = insights.chrome(home)
    css_files = glob.glob(os.path.join(root, "assets", "insights", "insights-*.css"))
    js_files = glob.glob(os.path.join(root, "assets", "insights", "insights-*.js"))
    if len(css_files) != 1 or len(js_files) != 1:
        raise insights.InsightsError("run tools/insights.py first: expected one insights-*.css and one insights-*.js")
    assets = {"css": "/assets/insights/" + os.path.basename(css_files[0]),
              "js": "/assets/insights/" + os.path.basename(js_files[0])}

def update_sitemap(root):
    p = os.path.join(root, "sitemap.xml")
    t = insights.read(p)
    loc = f"<loc>{BASE}{PATH}</loc>"
    if loc in t:
        return "sitemap.xml: /solutions/ already listed"
    entry = f"  <url>\n    {loc}\n    <changefreq>monthly</changefreq>\n    <priority>0.8</priority>\n  </url>\n"
    t = t.replace("</urlset>", entry + "</urlset>", 1)
    with open(p, "w", encoding="utf-8", newline="") as f:
        f.write(t)
    return "sitemap.xml: /solutions/ added"


def update_llms(root):
    p = os.path.join(root, "llms.txt")
    if not os.path.exists(p):
        return "llms.txt: not present"
    t = insights.read(p)
    line = f"- [Solutions]({BASE}{PATH}): what ScaleSafe does for each SEBI registration (IA, RA, PMS, AIF) and each compliance job."
    if "/solutions/" in t:
        return "llms.txt: Solutions already listed"
    m = re.search(r"^- \[Insights\].*$", t, re.M)
    t = t[:m.end()] + "\n" + line + t[m.end():] if m else t.rstrip("\n") + "\n" + line + "\n"
    with open(p, "w", encoding="utf-8", newline="") as f:
        f.write(t)
    return "llms.txt: Solutions added"


def generate(root):
    text = build(root)
    out = os.path.join(root, "solutions", "index.html")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    return ["solutions/index.html: built", update_sitemap(root), update_llms(root)]


def main():
    root = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "site-deploy")
    for n in generate(root):
        print("  -", n)


if __name__ == "__main__":
    main()
